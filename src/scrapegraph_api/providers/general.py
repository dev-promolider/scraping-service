"""General course catalogs available through documented provider APIs.

O'Reilly's Search MCP API needs a token generated by an authorized account.
See https://learning.oreilly.com/apidocs/mcp/content/ for its protocol and scope.
"""

from __future__ import annotations

import json
import os
import re
import unicodedata
from collections.abc import Callable
from urllib.parse import urlparse

import requests

from scrapegraph_api.providers.errors import SourceBlockedError


_MCP_URL = "https://api.oreilly.com/api/search/v1/mcp"
_NO_PRICE = "No disponible"
_STOPWORDS = {"a", "and", "course", "courses", "de", "del", "el", "en", "la", "los", "of", "para", "the", "y"}


class OReillyUnavailable(RuntimeError):
    """An authorized search could not be completed."""


class OReillyBlocked(OReillyUnavailable, SourceBlockedError):
    """O'Reilly denied the authorized token or rate-limited the API client."""


def _normalized(value: str) -> str:
    value = unicodedata.normalize("NFKD", value.casefold())
    return "".join(char for char in value if not unicodedata.combining(char))


def _relevant(topic: str, record: dict) -> bool:
    terms = [word for word in re.findall(r"[a-z0-9+#]+", _normalized(topic)) if word not in _STOPWORDS]
    if not terms:
        return False
    tags = record.get("tags")
    tag_text = " ".join(str(tag) for tag in tags) if isinstance(tags, list) else ""
    haystack = _normalized(f"{record.get('title', '')} {tag_text}")
    return all(term in haystack for term in terms)


def _request(session: requests.Session, body: dict, *, notification: bool = False) -> dict:
    try:
        response = session.post(_MCP_URL, json=body, timeout=(3, 8))
    except requests.RequestException as exc:
        raise OReillyUnavailable("No se pudo consultar la API oficial de O'Reilly") from exc
    if response.status_code in (401, 403):
        raise OReillyBlocked("El token de O'Reilly no tiene acceso a la búsqueda")
    if response.status_code == 429:
        raise OReillyBlocked("O'Reilly limitó las consultas; se debe pausar esta fuente")
    try:
        response.raise_for_status()
    except requests.HTTPError as exc:
        raise OReillyUnavailable(f"La API de O'Reilly respondió HTTP {response.status_code}") from exc
    session_id = response.headers.get("Mcp-Session-Id")
    if session_id:
        session.headers["Mcp-Session-Id"] = session_id
    if notification and response.status_code == 202:
        return {}
    try:
        payload = response.json()
    except requests.ValueError as exc:
        raise OReillyUnavailable("O'Reilly devolvió una respuesta no JSON") from exc
    if not isinstance(payload, dict) or "error" in payload:
        raise OReillyUnavailable("O'Reilly devolvió un error de protocolo")
    return payload


def oreilly(topic: str, max_items: int) -> list[dict[str, str]]:
    """Search authorized course metadata; never access course content."""
    topic = topic.strip()
    if not topic or max_items <= 0:
        return []
    token = os.environ.get("OREILLY_MCP_TOKEN", "").strip()
    if not token:
        raise OReillyUnavailable("Falta OREILLY_MCP_TOKEN para consultar O'Reilly")

    with requests.Session() as session:
        session.headers.update({
            "Authorization": f"Bearer {token}",
            "Accept": "application/json, text/event-stream",
        })
        initialized = _request(session, {
            "jsonrpc": "2.0",
            "method": "initialize",
            "params": {
                "protocolVersion": "2025-06-18",
                "capabilities": {},
                "clientInfo": {"name": "pickle-course-catalog", "version": "1.0"},
            },
            "id": 0,
        })
        if not isinstance(initialized.get("result"), dict):
            raise OReillyUnavailable("O'Reilly no confirmó la sesión de búsqueda")
        _request(session, {"jsonrpc": "2.0", "method": "notifications/initialized"}, notification=True)
        answer = _request(session, {
            "jsonrpc": "2.0",
            "method": "tools/call",
            "params": {
                "name": "search_oreilly_content",
                "arguments": {"query": topic[:500], "n_items": min(max_items, 100), "content_types": ["courses"]},
            },
            "id": 1,
        })

    result = answer.get("result")
    if not isinstance(result, dict) or result.get("isError"):
        raise OReillyUnavailable("O'Reilly no pudo completar la búsqueda")
    blocks = result.get("content")
    if not isinstance(blocks, list):
        raise OReillyUnavailable("O'Reilly cambió el formato de la búsqueda")
    courses: list[dict[str, str]] = []
    seen: set[str] = set()
    for block in blocks:
        if not isinstance(block, dict) or block.get("type") != "text":
            continue
        try:
            search_results = json.loads(str(block.get("text", ""))).get("search_results")
        except (json.JSONDecodeError, AttributeError) as exc:
            raise OReillyUnavailable("O'Reilly cambió el formato de los resultados") from exc
        if not isinstance(search_results, dict):
            raise OReillyUnavailable("O'Reilly cambió el formato de los resultados")
        for record in search_results.values():
            if not isinstance(record, dict) or not _relevant(topic, record):
                continue
            url = str(record.get("url") or "")
            parsed = urlparse(url)
            title = " ".join(str(record.get("title") or "").split())
            if not title or parsed.scheme != "https" or parsed.hostname != "learning.oreilly.com" or url in seen:
                continue
            seen.add(url)
            description = record.get("description")
            if not isinstance(description, str):
                description = ""
            courses.append({"title": title, "description": " ".join(description.split()), "price": _NO_PRICE, "url": url})
            if len(courses) >= max_items:
                return courses
    return courses


ADAPTERS: dict[str, Callable[[str, int], list[dict[str, str]]]] = {"oreilly": oreilly}
